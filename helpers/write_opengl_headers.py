"""Write the headers of OpenGL.framework.

usage: write_opengl_headers.py GL_XML DATA_DIR OUT_DIR DATE

GL_XML is the OpenGL Registry's gl.xml, DATA_DIR the data/opengl directory of this
repository, OUT_DIR the Headers directory of the framework.  Writes
  gltypes.h gl.h gl3.h glext.h gl3ext.h   from gl.xml (Apache-2.0, the notice of gl.xml is
                                          at the top of each file)
  OpenGL.h CGLTypes.h CGLCurrent.h CGLDevice.h CGLIOSurface.h CGLRenderers.h
                                          from the data files (0BSD)
gl.h is the legacy profile (OpenGL 1.0 to 2.1, with what the later versions removed),
gl3.h the core profile (3.2 to 4.1); docs/SOURCES.md names the source of every header.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # python3 -I leaves it out
import gl_registry as R  # noqa: E402

# The GL types of gl.xml's <types> that the headers use, with the C types of Khronos'
# platform header (KHR/khrplatform.h: khronos_int8_t is int8_t, khronos_float_t is float,
# khronos_intptr_t is intptr_t, khronos_ssize_t is signed long on LP64).
TYPES = [
    ("GLenum", "unsigned int"), ("GLboolean", "unsigned char"), ("GLbitfield", "unsigned int"),
    ("GLvoid", "void"), ("GLbyte", "signed char"), ("GLubyte", "unsigned char"),
    ("GLshort", "short"), ("GLushort", "unsigned short"), ("GLint", "int"),
    ("GLuint", "unsigned int"), ("GLsizei", "int"), ("GLfloat", "float"),
    ("GLclampf", "float"), ("GLdouble", "double"), ("GLclampd", "double"),
    ("GLchar", "char"), ("GLintptr", "intptr_t"), ("GLsizeiptr", "long"),
    ("GLint64", "int64_t"), ("GLuint64", "uint64_t"), ("GLsync", "struct __GLsync *"),
]


def head(path_comment, lines):
    return "/* %s */\n" % path_comment + "".join("/* %s */\n" % l for l in lines)


def gl_notice(reg, date):
    c = reg.copyright_lines()
    return ("/*\n** Generated by osxcross-open-sdk (%s) from the OpenGL Registry's gl.xml\n"
            "** (https://github.com/KhronosGroup/OpenGL-Registry).\n"
            "**\n" % date) + "".join("** %s\n" % l for l in c) + "*/\n"


def own_notice(date):
    return ("/*\n** Generated by osxcross-open-sdk (%s) from data/opengl/.\n"
            "** SPDX-License-Identifier: 0BSD\n*/\n" % date)


def guard(name, body, extern_c=True):
    s = "#ifndef %s\n#define %s 1\n\n" % (name, name)
    if extern_c:
        s += "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
    s += body
    if extern_c:
        s += "\n#ifdef __cplusplus\n}\n#endif\n"
    return s + "\n#endif /* %s */\n" % name


def enum_line(reg, name):
    val, typ = reg.enums[name]
    suffix = {"u": "u", "ull": "ull"}.get(typ, "")
    return "#define %-40s %s%s\n" % (name, val, suffix)


def feature_blocks(reg, sel):
    s = ""
    for fname, enums, cmds in sel:
        if not enums and not cmds:
            continue
        # no #ifndef guard: gl.h and gl3.h may be included together (the macros are the
        # same in both, and so are the prototypes)
        s += "#define %s 1\n" % fname
        for e in enums:
            s += enum_line(reg, e)
        for c in cmds:
            s += reg.commands[c].declaration() + "\n"
        s += "\n"
    return s


def types_h(reg, date):
    body = "#include <stdint.h>\n\n"
    for n, t in TYPES:
        if n not in reg.types:
            raise SystemExit("gl.xml has no type %s" % n)
        if t.endswith("*"):
            body += "typedef %s%s;\n" % (t, n)
        else:
            body += "typedef %s %s;\n" % (t, n)
    return gl_notice(reg, date) + guard("__gltypes_h_", body, False)


def ext_blocks(reg, droot):
    """The extensions of data/opengl/extensions.txt: (name, tokens, declared commands)"""
    res = []
    for name, funcs, _pages in R.read_pipe_file(os.path.join(droot, "extensions.txt")):
        x = reg.extensions[name]
        tokens = []
        cmds = []
        for _prof, items in x.requires:
            for k, n in items:
                if k == "enum":
                    tokens.append(n)
        for f in funcs.split():
            if not any(("command", f) in items for _p, items in x.requires):
                raise SystemExit("%s does not have %s in gl.xml" % (name, f))
            cmds.append(f)
        res.append((name, tokens, cmds))
    return res


def write(path, text):
    with open(path, "w") as f:
        f.write(text)


def cgl_types_h(droot, date):
    enums = R.read_cgl_enums(os.path.join(droot, "cgl-enums.txt"))
    names = {"error": "CGLError", "pfa": "CGLPixelFormatAttribute", "rp": "CGLRendererProperty",
             "ce": "CGLContextEnable", "cp": "CGLContextParameter", "go": "CGLGlobalOption",
             "oglp": "CGLOpenGLProfile"}
    body = "#include <OpenGL/gltypes.h>\n\n"
    for t in ("ContextObj", "PixelFormatObj", "RendererInfoObj", "PBufferObj", "ShareGroupObj"):
        body += "typedef struct _CGL%s *CGL%s;\n" % (t.replace("Obj", "Object"), t)
    body += "\n"
    for g in ("error", "pfa", "rp", "ce", "cp", "go", "oglp"):
        rows = [(n, v) for gg, n, v in enums if gg == g]
        body += "typedef enum _%s {\n" % names[g]
        body += ",\n".join("  %s = %s" % (n, v) for n, v in rows)
        body += "\n} %s;\n\n" % names[g]
    return own_notice(date) + guard("_CGLTYPES_H", body)


def cgl_header(droot, date, fname, funcs, includes, extra=""):
    body = "".join("#include <OpenGL/%s>\n" % i for i in includes) + "\n" + extra
    for h, ret, n, params, _src in funcs:
        if h == fname:
            sep = "" if ret.endswith("*") else " "
            body += "extern %s%s%s(%s);\n" % (ret, sep, n, params)
    return own_notice(date) + guard("_" + fname.upper().replace(".", "_"), body)


def main(argv):
    if len(argv) != 5:
        print(__doc__, file=sys.stderr)
        return 2
    glxml, droot, out, date = argv[1:]
    reg = R.Registry(glxml)
    os.makedirs(out, exist_ok=True)

    write(os.path.join(out, "gltypes.h"), types_h(reg, date))

    legacy = reg.select((1, 0), R.LEGACY_MAX, "compatibility")
    body = "#include <OpenGL/gltypes.h>\n\n" + feature_blocks(reg, legacy)
    write(os.path.join(out, "gl.h"), gl_notice(reg, date) + guard("__gl_h_", body))

    core = reg.select((1, 0), R.CORE_MAX, "core")
    body = "#include <OpenGL/gltypes.h>\n\n" + feature_blocks(reg, core)
    write(os.path.join(out, "gl3.h"), gl_notice(reg, date) + guard("__gl3_h_", body))

    # glext.h: the extensions of data/opengl/extensions.txt.  gl3ext.h has none: no source says
    # which extensions a core profile context has.
    body = "#include <OpenGL/gltypes.h>\n\n"
    for name, tokens, cmds in ext_blocks(reg, droot):
        body += "#define %s 1\n" % name
        for t in tokens:
            body += enum_line(reg, t)
        for c in cmds:
            body += reg.commands[c].declaration() + "\n"
        body += "\n"
    write(os.path.join(out, "glext.h"), gl_notice(reg, date) + guard("__glext_h_", body))
    write(os.path.join(out, "gl3ext.h"), gl_notice(reg, date) + guard(
        "__gl3ext_h_", "#include <OpenGL/gltypes.h>\n\n/* No extension is declared here. */\n"))

    funcs = [r for r in R.read_pipe_file(os.path.join(droot, "cgl-functions.txt"))]
    write(os.path.join(out, "CGLTypes.h"), cgl_types_h(droot, date))
    write(os.path.join(out, "CGLCurrent.h"), cgl_header(droot, date, "CGLCurrent.h", funcs, ["CGLTypes.h"]))
    write(os.path.join(out, "CGLDevice.h"), cgl_header(droot, date, "CGLDevice.h", funcs, ["CGLTypes.h"]))
    write(os.path.join(out, "CGLIOSurface.h"), cgl_header(
        droot, date, "CGLIOSurface.h", funcs, ["CGLTypes.h"],
        "#ifndef __IOSURFACE_H\ntypedef struct __IOSurface *IOSurfaceRef;\n#endif\n\n"))
    write(os.path.join(out, "OpenGL.h"), cgl_header(
        droot, date, "OpenGL.h", funcs, ["CGLTypes.h", "CGLCurrent.h", "CGLDevice.h"]))
    rend = [(n, v) for g, n, v in R.read_cgl_enums(os.path.join(droot, "cgl-enums.txt")) if g == "renderer"]
    body = "#include <OpenGL/CGLTypes.h>\n\n" + "".join("#define %s %s\n" % (n, v) for n, v in rend)
    write(os.path.join(out, "CGLRenderers.h"), own_notice(date) + guard("_CGLRENDERERS_H", body))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
