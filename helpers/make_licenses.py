def commit_of(src, d):
    r = subprocess.run(["git", "--git-dir", os.path.join(src, d.split("/")[0], ".git"), "rev-parse", "HEAD"],
                       stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, universal_newlines=True)
    return r.stdout.strip() or "?"


def tag_of(src, d):
    p = os.path.join(src, d.split("/")[0], ".oc-tag")
    return open(p).read().strip() if os.path.exists(p) else "?"


def sqlite_version(header):
    """The version that sqlite3.h defines (SQLITE_VERSION)"""
    m = re.search(r'^#define SQLITE_VERSION\s+"([^"]+)"', open(header).read(), re.M)
    if not m:
        sys.exit("make_licenses.py: %s has no SQLITE_VERSION" % header)
    return m.group(1)


def header_notice(path):
    t = open(path, errors="replace").read()
    m = re.search(r"/\*.*?\*/", t, re.S)
    return m.group(0) if m else t[:3000]


def install(src, out, variant, apache, sqlite, swift_lic):
    """Copy the license texts; [(name, tag, license, what, note)], [(project, tag, commit)]"""
    apsl = os.path.join(src, "xnu/APPLE_LICENSE")
    rows = []
    projects = []
    for ent in P:
        name, d, lic, what, var = ent[:5]
        extra = ent[5] if len(ent) > 5 else []
        notice = ent[6] if len(ent) > 6 else None
        if var not in WANT[variant] and not (var == "swift" and swift_lic):
            continue
        dst = os.path.join(out, name.replace(" ", "-"))
        os.makedirs(dst, exist_ok=True)
        note = ""
        if name == "sqlite":
            h = os.path.join(sqlite, "sqlite3.h") if sqlite else None
            if not h or not os.path.exists(h):
                continue
            with open(os.path.join(dst, "NOTICE.txt"), "w") as f:
                f.write(header_notice(h) + "\n")
            version = sqlite_version(h)
            tag = "%s (%s)" % (version, os.path.basename(os.path.normpath(sqlite)))
            what = what.replace("{version}", version)
            note = "notice block copied from sqlite3.h (SQLite has no license file)"
        elif name == "Swift runtime stubs":
            shutil.copy(swift_lic, os.path.join(dst, "LICENSE.txt"))
            tag = "swift.org package"
        else:
            base = os.path.join(src, d)
            tag = tag_of(src, d) if not name.startswith("LLVM") else tag_of(src, "llvm-project")
            what = what.replace("{tag}", tag)
            found = []
            for f in sorted(os.listdir(base)):
                if LIC.match(f) and os.path.isfile(os.path.join(base, f)):
                    shutil.copy(os.path.join(base, f), os.path.join(dst, f))
                    found.append(f)
            for e in extra:
                p = os.path.normpath(os.path.join(base, e))
                if os.path.isfile(p):
                    shutil.copy(p, os.path.join(dst, os.path.basename(p)))
                    found.append(os.path.basename(p))
            if not found:
                if notice and os.path.exists(os.path.join(base, notice)):
                    with open(os.path.join(dst, "NOTICE-from-" + os.path.basename(notice) + ".txt"), "w") as f:
                        f.write(header_notice(os.path.join(base, notice)) + "\n")
                    note = "no license file in the project; notice block copied from " + notice
                if lic.startswith("Apache License 2.0"):
                    # the notice of the headers only names the license; section 4(a) asks for a copy
                    shutil.copy(apache, os.path.join(dst, "LICENSE-Apache-2.0.txt"))
                    note += ("; " if note else "") + "text of the Apache License 2.0 added (apache.org/licenses/LICENSE-2.0.txt)"
                if "APSL" in lic:
                    shutil.copy(apsl, os.path.join(dst, "APPLE_LICENSE (APSL 2.0, from xnu)"))
                    note += ("; " if note else "") + "APSL 2.0 text from xnu/APPLE_LICENSE added"
                if not os.listdir(dst):
                    note = "no license text found"
        rows.append((name, tag, lic, what, note))
        if name not in ("sqlite", "Swift runtime stubs"):
            p = (name.replace("LLVM libc++abi", "llvm-project").replace("LLVM libc++", "llvm-project"), tag, commit_of(src, d))
            if p not in projects:
                projects.append(p)
    return rows, projects


def main(argv):
    ap = argparse.ArgumentParser(prog="make_licenses.py", description="Install the license texts.")
    ap.add_argument("src")
    ap.add_argument("out")
    ap.add_argument("variant", choices=sorted(WANT))
    ap.add_argument("own_license", help="the license of the files written for the SDK (0BSD)")
    ap.add_argument("--apache-license", required=True, help="the text of the Apache License 2.0")
    ap.add_argument("--sqlite", help="the directory of the sqlite amalgamation")
    ap.add_argument("--swift-license")
    ap.add_argument("--projects-out")
    a = ap.parse_args(argv[1:])
    out = a.out
    os.makedirs(out, exist_ok=True)
    rows, projects = install(a.src, out, a.variant, a.apache_license, a.sqlite, a.swift_license)
    with open(os.path.join(out, "LICENSES.md"), "w") as f:
        f.write("# Licenses of the open SDK (%s)\n\n" % TITLE[a.variant])
        f.write("Every directory next to this file holds the full license text(s) taken from the source tag the SDK\n"
                "files were made from. Headers keep their own copyright notices.\n\n")
        f.write("| Project | Tag | License | What in the SDK comes from it | Note |\n|---|---|---|---|---|\n")
        for r in rows:
            f.write("| %s | %s | %s | %s | %s |\n" % r)
        f.write(OWN_FILES_TEXT)
    os.makedirs(os.path.join(out, "own-files-0BSD"), exist_ok=True)
    shutil.copy(a.own_license, os.path.join(out, "own-files-0BSD", "LICENSE.txt"))
    if a.projects_out:
        with open(a.projects_out, "w") as f:
            for p in sorted(projects):
                f.write("%s\t%s\t%s\n" % p)
    shutil.copy(os.path.join(out, "LICENSES.md"), os.path.join(out, "README.txt"))
    print("%d projects" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
