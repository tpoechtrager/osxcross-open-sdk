# run_unifdef ARGS...: the unifdef of the step host.  Its status 1 means that
# it changed the file, not an error (2 is one).
run_unifdef() { "$HOST/bin/unifdef" "$@" || [ $? -eq 1 ]; }

# copy_headers FROM TO UNIFDEF-FLAG...: copy the headers of the directory FROM
# to TO, each through unifdef -t with the flags
copy_headers() {
  local from=$1 to=$2 f; shift 2
  mkdir -p "$to"
  (cd "$from" && find . -name '*.h' -type f) | while read -r f; do
    mkdir -p "$to/$(dirname "$f")"
    run_unifdef -t "$@" -o "$to/$f" "$from/$f"
  done
}

step_headers() {
  local I=$STAGE/usr/include a h
  rm -rf "$STAGE"; mkdir -p "$I" "$STAGE/work"
  fix_shebangs

  log "Headers"
  echo "Installed into usr/include from the projects:"
  echo "   xnu"
  # (its count of files is not shown: the last line has the total)
  quiet python3 -I "$HELPERS/xnu_headers.py" "$SRC/xnu" "$STAGE/xnu" "$HOST/bin/unifdef" "$HOST/bin/decomment"
  copy_tree "$STAGE/xnu/usr/include" "$I"
  rm -f "$I/pthread/bsdthread_private.h" "$I/pthread/priority_private.h" \
        "$I/pthread/workqueue_syscalls.h" "$I/security/mac.h"
  # headers generated by xnu's own scripts
  mkdir -p "$STAGE/gen/sdkroot/usr/local/libexec" "$STAGE/gen/work"
  headers_availability
  cp "$STAGE/avail/availability" "$STAGE/gen/sdkroot/usr/local/libexec/availability.pl"
  sh "$SRC/xnu/bsd/sys/make_posix_availability.sh" "$I/sys/_posix_availability.h"
  bash "$SRC/xnu/bsd/sys/make_symbol_aliasing.sh" "$STAGE/gen/sdkroot" "$I/sys/_symbol_aliasing.h"
  (cd "$STAGE/gen/work" && run_unifdef "$SRC/xnu/bsd/kern/syscalls.master" > bsd.syscalls.master
   run_logged "$STAGE/gen/makesyscalls.log" sh "$SRC/xnu/bsd/kern/makesyscalls.sh" bsd.syscalls.master header
   cp syscall.h "$I/sys/syscall.h")
  cp "$SRC"/xnu/EXTERNAL_HEADERS/AssertMacros.h "$I/"
  mkdir -p "$I/mach-o" "$I/mach-o/x86_64" "$I/mach-o/arm" "$I/mach-o/arm64"
  cp "$SRC"/xnu/EXTERNAL_HEADERS/mach-o/{fat,fixup-chains,loader,nlist,reloc,stab}.h "$I/mach-o/"
  for a in x86_64 arm arm64; do cp "$SRC/xnu/EXTERNAL_HEADERS/mach-o/$a/reloc.h" "$I/mach-o/$a/"; done

  echo "   Libsyscall"
  mkdir -p "$STAGE/libsyscall/obj" "$STAGE/libsyscall/products"
  run_logged "$STAGE/libsyscall/mig.log" aenv SRCROOT="$SRC/xnu/libsyscall" OBJROOT="$STAGE/libsyscall/obj" \
    BUILT_PRODUCTS_DIR="$STAGE/libsyscall/products" ARCHS="x86_64 arm64" PLATFORM_NAME=macosx \
    MIGCOM="$HOST/bin/migcom" bash -e "$SRC/xnu/libsyscall/xcodescripts/mach_install_mig.sh"
  copy_tree "$STAGE/libsyscall/products/mig_hdr/include" "$I"

  echo "   Libc"
  mkdir -p "$STAGE/libc/derived"
  run_logged "$STAGE/libc/headers.log" aenv SRCROOT="$SRC/Libc" DSTROOT="$STAGE/libc" SDK_INSTALL_HEADERS_ROOT= PLATFORM_NAME=macosx \
    VARIANT_PLATFORM_NAME=macosx ARCHS="x86_64 arm64" DERIVED_FILES_DIR="$STAGE/libc/derived" \
    DEPLOYMENT_LOCATION=YES bash -e "$SRC/Libc/xcodescripts/headers.sh"
  copy_tree "$STAGE/libc/usr/include" "$I"

  echo "   AvailabilityVersions"
  cp "$STAGE"/avail/Availability*.h "$I/"
  mkdir -p "$I/os"; cp "$STAGE/avail/os_availability.h" "$I/os/availability.h"

  printf '   %s\n' libpthread libplatform libmalloc libclosure libdispatch
  copy_headers "$SRC/libpthread/include/pthread" "$I/pthread" -U__PTHREAD_BUILDING_PTHREAD__
  copy_headers "$SRC/libpthread/include/sys" "$I/sys" -U__PTHREAD_BUILDING_PTHREAD__
  for h in pthread pthread_impl pthread_spis sched; do cp "$I/pthread/$h.h" "$I/$h.h"; done
  cp "$SRC"/libplatform/include/{setjmp,string_x86,ucontext}.h "$I/"
  cp "$SRC"/libplatform/include/libkern/*.h "$I/libkern/"
  cp "$SRC"/libplatform/include/os/lock.h "$I/os/"
  # (newer releases only)
  if [ -f "$SRC/libplatform/include/os/os_sync_wait_on_address.h" ]; then
    cp "$SRC/libplatform/include/os/os_sync_wait_on_address.h" "$I/os/"
  fi
  mkdir -p "$I/malloc"; cp "$SRC"/libmalloc/include/malloc/*.h "$I/malloc/"
  cp "$SRC/libclosure/Block.h" "$I/"
  copy_headers "$SRC/libdispatch/dispatch" "$I/dispatch" -U__DISPATCH_BUILDING_DISPATCH__ -U__linux__ -DTARGET_OS_WIN32=0 -U__ANDROID__
  for h in object workgroup workgroup_base workgroup_interval workgroup_object workgroup_parallel clock; do
    # (the headers of workgroups and clocks are in newer releases only)
    [ -f "$SRC/libdispatch/os/$h.h" ] || continue
    run_unifdef -t -U__DISPATCH_BUILDING_DISPATCH__ -U__linux__ -DTARGET_OS_WIN32=0 -U__ANDROID__ \
      -o "$I/os/$h.h" "$SRC/libdispatch/os/$h.h"
  done

  printf '   %s\n' Libinfo libresolv Libnotify copyfile removefile Librpcsvc syslog
  mkdir -p "$STAGE/libinfo"
  to_log "$STAGE/libinfo.log" headers_libinfo_install ||
    { tail -n 20 "$STAGE/libinfo.log" >&2; die "the install script of Libinfo failed"; }
  [ -f "$STAGE/libinfo/usr/include/netdb.h" ] || die "the install script of Libinfo installed no netdb.h"
  copy_tree "$STAGE/libinfo/usr/include" "$I"
  for h in dns dns_util nameser resolv; do cp "$SRC/libresolv/$h.h" "$I/"; done
  # libresolv/xcodescripts/headers.sh: arpa/nameser.h is a link to ../nameser.h
  mkdir -p "$I/arpa"; ln -sf ../nameser.h "$I/arpa/nameser.h"
  cp "$SRC"/Libnotify/{notify,notify_keys}.h "$I/"
  cp "$SRC"/copyfile/{copyfile,xattr_flags}.h "$I/"
  cp "$SRC"/removefile/{removefile,checkint}.h "$I/"
  cp "$SRC/Libc/gen/get_compat.h" "$I/"

  printf '   %s\n' dyld libunwind Libm objc4 architecture
  cp "$SRC/dyld/include/dlfcn.h" "$I/"
  for h in dyld dyld_images fixup-chains utils; do
    if [ -f "$SRC/dyld/include/mach-o/$h.h" ]; then cp "$SRC/dyld/include/mach-o/$h.h" "$I/mach-o/"; fi
  done
  # libmacho headers (mach-o/getsect.h is needed by libgcc's darwin-crt-tm.c)
  mkdir -p "$I/mach-o/i386"
  for h in arch getsect ldsyms swap ranlib; do cp "$SRC/cctools/include/mach-o/$h.h" "$I/mach-o/"; done
  cp "$SRC/cctools/include/mach-o/i386/swap.h" "$I/mach-o/i386/"
  cp "$SRC"/libunwind/libunwind/include/{libunwind,unwind,__libunwind_config}.h "$I/"
  cp "$SRC/libunwind/libunwind/include/mach-o/compact_unwind_encoding.h" "$I/mach-o/"
  cp "$SRC"/Libm/Source/{math,fenv,complex}.h "$I/"
  # Libm-2026 predates arm64 macOS: use the ARM variants for arm64 too
  # (<fenv.h> assumes a 32-bit VFP: arm64 gets its own header, data/headers/fenv-arm64.h)
  sed_inplace "$I/math.h" 's/defined(__arm__)/defined(__arm__) || defined(__arm64__)/'
  sed_inplace "$I/complex.h" 's/defined(__arm__)/defined(__arm__) || defined(__arm64__)/'
  perl -pi -e 's/^#elif defined\(__arm__\)$/#elif defined(__arm64__) || defined(__aarch64__)\n#include "architecture\/arm64\/fenv.h"\n#elif defined(__arm__)/' "$I/fenv.h"
  add_notice "$I/math.h" "the ARM branches are also used for arm64"
  add_notice "$I/complex.h" "the ARM branches are also used for arm64"
  add_notice "$I/fenv.h" "a branch for arm64 added that includes architecture/arm64/fenv.h"
  mkdir -p "$I/architecture/i386" "$I/architecture/arm" "$I/architecture/arm64"
  cp "$DATA/headers/fenv-arm64.h" "$I/architecture/arm64/fenv.h"
  cp "$SRC"/Libm/Source/Intel/{math,fenv}.h "$I/architecture/i386/"
  cp "$SRC"/Libm/Source/ARM/{math,fenv}.h "$I/architecture/arm/"
  # The ARM math.h hides llrint*/llround* in strict ISO C++ mode (it tests the C
  # standard version); with GCC's libstdc++ configure (-std=c++98 probes) that
  # turns off the C99 rounding functions.  Use the test of Libm's Intel
  # math.h: only __DARWIN_NO_LONG_LONG hides the long long variants.
  sed_inplace "$I/architecture/arm/math.h" 's/^#if ( defined (__STDC_VERSION__) && __STDC_VERSION__ >= 199901L ) || ! defined( __STRICT_ANSI__ )  || ! defined( __GNUC__ )$/#if !(__DARWIN_NO_LONG_LONG)/'
  add_notice "$I/architecture/arm/math.h" "the condition that hides the long long functions is the one of the Intel math.h"
  headers_objc "$I"
  # (architecture/arm and architecture/i386 have Libm's math.h and fenv.h from
  # above; the headers of the project architecture are added to them)
  cp -r "$SRC"/architecture/{alignment.h,byte_order.h,arm,i386} "$I/architecture/"
  cp "$SRC"/xnu/libsyscall/wrappers/spawn/spawn.h "$SRC"/xnu/libsyscall/wrappers/gethostuuid.h \
     "$SRC"/xnu/libsyscall/wrappers/libproc/libproc.h "$I/"
  cp "$SRC"/syslog/libsystem_asl.tproj/include/asl.h "$I/"

  headers_target_conditionals "$I"
  headers_os_log "$I"
  headers_fixups "$I"
  headers_check "$I"
  # the headers of this step: gen_symbols.py takes the symbols of libSystem from them
  (cd "$I" && find . ! -type d -name '*.h' | sed 's#^\./##' | sort) > "$STAGE/work/headers.list"
}

# headers_libinfo_install: the part of Libinfo's install script before the man
# pages, which installs the headers into $STAGE/libinfo
headers_libinfo_install() {
  (cd "$SRC/Libinfo" && aenv PLATFORM_NAME=macosx DSTROOT="$STAGE/libinfo" INSTALL_OWNER="$(id -un)" \
     INSTALL_GROUP="$(id -gn)" ACTION=installhdrs SRCROOT="$SRC/Libinfo" \
     OC_SCRIPT="$STAGE/libinfo.sh" \
     bash -c 'sed -n "1,/^# Don.t install man pages/p" xcodescripts/install_files.sh | sed '"'"'$d'"'"' > "$OC_SCRIPT"; bash -e "$OC_SCRIPT"; rm -f "$OC_SCRIPT"')
}

# The headers that every SDK has.  A step that "worked" but left one of them
# out (a Makefile that listed nothing, a script that failed quietly) must stop
# the build.
headers_check() {
  local I=$1 h missing=
  for h in stdio.h stdlib.h string.h unistd.h pthread.h math.h fenv.h setjmp.h signal.h netdb.h pwd.h grp.h \
           sys/types.h sys/syscall.h sys/_posix_availability.h sys/_symbol_aliasing.h mach/mach.h mach/message.h \
           mach-o/loader.h mach-o/dyld.h dispatch/dispatch.h malloc/malloc.h objc/runtime.h libkern/OSByteOrder.h \
           Availability.h AvailabilityMacros.h os/availability.h TargetConditionals.h dlfcn.h dns.h resolv.h \
           copyfile.h notify.h removefile.h libunwind.h Block.h architecture/arm64/fenv.h; do
    [ -s "$I/$h" ] || missing="$missing $h"
  done
  [ -z "$missing" ] || die "the header step did not install:$missing"
}

headers_availability() {
  local A=$SRC/AvailabilityVersions O=$STAGE/avail V=$STAGE/avail-src h
  mkdir -p "$O"
  # Apple's generator, with the DSL cut after this SDK's release (and
  # continued by data/availability-extra.dsl for releases after 14.3)
  mkdir -p "$V"; copy_tree "$A" "$V"
  python3 -I "$HELPERS/avail_dsl.py" "$A/availability.dsl" "$DATA/availability-extra.dsl" \
    "$SDK_VERSION" "$V/availability.dsl"
  python3 -I "$V/availability" --preprocess "$V/availability" "$O/availability"
  for h in Availability.h AvailabilityInternal.h AvailabilityInternalLegacy.h AvailabilityMacros.h \
           AvailabilityVersions.h os_availability.h; do
    python3 -I "$O/availability" --preprocess "$V/templates/$h" "$O/$h"
  done
}

headers_objc() {
  local I=$1 h
  mkdir -p "$I/objc"
  for h in NSObjCRuntime NSObject Object Protocol hashtable hashtable2 message objc-api objc-auto \
           objc-class objc-exception objc-load objc-runtime objc-sync objc runtime; do
    run_unifdef -t -DBUILD_FOR_OSX -o "$I/objc/$h.h" "$SRC/objc4/runtime/$h.h"
  done
  run_unifdef -t -DBUILD_FOR_OSX -o "$I/objc/List.h" "$SRC/objc4/runtime/OldClasses.subproj/List.h"
}

# The published sources have a few places where internal-only lines were
# scrubbed (#ifndef __OPEN_SOURCE__ blocks).  Repair what breaks compilation.
headers_fixups() {
  local I=$1
  # dyld.h: DYLD_EXCLAVEKIT_UNAVAILABLE is defined in a scrubbed block and one
  # declaration lost its terminating semicolon
  sed_inplace "$I/mach-o/dyld.h" 's/^\(extern NSObjectFileImageReturnCode NSCreateObjectFileImageFromFile.*__OSX_DEPRECATED([^)]*)\)[[:blank:]]*$/\1;/'
  perl_first_include "$I/mach-o/dyld.h" '#ifndef DYLD_EXCLAVEKIT_UNAVAILABLE\n#define DYLD_EXCLAVEKIT_UNAVAILABLE\n#endif\n'
  add_notice "$I/mach-o/dyld.h" "a missing semicolon added and DYLD_EXCLAVEKIT_UNAVAILABLE defined"
  # dyld_images.h: needs uintptr_t, mach_port_t ... (include was scrubbed)
  perl_first_include "$I/mach-o/dyld_images.h" '#include <stdint.h>\n#include <unistd.h>\n#include <mach/mach.h>\n'
  add_notice "$I/mach-o/dyld_images.h" "includes of stdint.h, unistd.h and mach/mach.h added"
  # string_x86.h needs sys/cdefs.h
  perl_first_include "$I/string_x86.h" '#include <sys/cdefs.h>\n'
  add_notice "$I/string_x86.h" "include of sys/cdefs.h added"
  # mach/port.h (xnu of macOS 26.4 and later): xnu_static_assert_struct_size is
  # _Static_assert, which GCC knows only in C (clang also in C++), so mach/message.h
  # does not compile with g++.  In C++ the macro is static_assert from C++11 on;
  # before C++11 there is no static assertion and the macro is a typedef that can
  # be repeated.  Releases before this xnu do not have the macros.
  if grep -q '^#define xnu_static_assert_struct_size_kernel_user(' "$I/mach/port.h"; then
    OC_TEXT='/*
 * Modified by osxcross-open-sdk ('"$NOTICE_DATE"'): GCC accepts _Static_assert only in C.
 * In C++ the macro uses static_assert (C++11 and later) or, before C++11, declares
 * a typedef that stands for no check.  In C it is unchanged.
 */
#ifdef __cplusplus
#undef xnu_static_assert_struct_size
#if __cplusplus >= 201103L
#if __arm64__
#define xnu_static_assert_struct_size(name, expected_size) static_assert(\
	sizeof(name) == expected_size, "the size of a Mach structure changed")
#else /* __arm64__ */
#define xnu_static_assert_struct_size(name, expected_size) static_assert(1, "size not checked on this architecture")
#endif /* __arm64__ */
#else /* __cplusplus >= 201103L */
#define xnu_static_assert_struct_size(name, expected_size) typedef char xnu_static_assert_unavailable_before_cxx11[1]
#endif /* __cplusplus >= 201103L */
#endif /* __cplusplus */

' perl -0pi -e 's/^(#define xnu_static_assert_struct_size_kernel_user\()/$ENV{OC_TEXT}$1/m' "$I/mach/port.h"
    grep -q 'Modified by osxcross-open-sdk' "$I/mach/port.h" || die "mach/port.h: the repair of xnu_static_assert_struct_size did not apply"
  fi
  # math.h: the published Libm does not declare __exp10 and __exp10f, the
  # functions that Clang calls for exp10 and pow(10, x) and that libSystem.tbd
  # lists (data/symbols/libsystem-extra.txt).  configure scripts that find
  # them by linking call them without a declaration otherwise (jq 1.8.0:
  # "call to undeclared library function '__exp10'").  The names and the
  # signature (double or float to the same type) are those of LLVM's
  # RuntimeLibcalls.td (DarwinExp10).
  perl -0pi -e 's|(#endif /\* __MATH_H__ \*/\s*)$|/* osxcross-open-sdk: the C library functions that Clang calls for exp10 (LLVM: RuntimeLibcalls.td) */\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern float __exp10f(float);\nextern double __exp10(double);\n#ifdef __cplusplus\n}\n#endif\n\n$1|' "$I/math.h"
  grep -q '__exp10f' "$I/math.h" || die "math.h has no __MATH_H__ guard end: the declaration of __exp10 was not added"
  add_notice "$I/math.h" "declarations of __exp10 and __exp10f added"
}

headers_target_conditionals() {
  cp "$DATA/headers/TargetConditionals.h" "$1/TargetConditionals.h"
}

# os/log.h: written here (see docs/SOURCES.md); xnu installs its own only into Kernel.framework.
# os/signpost.h, os/activity.h, os/trace.h: stand-ins that trace nothing.
headers_os_log() {
  mkdir -p "$1/os"
  cp "$DATA/headers/os-log.h" "$1/os/log.h"
  cp "$DATA/headers/os-signpost.h" "$1/os/signpost.h"
  cp "$DATA/headers/os-activity.h" "$1/os/activity.h"
  cp "$DATA/headers/os-trace.h" "$1/os/trace.h"
}
